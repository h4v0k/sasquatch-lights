// ELK-BLEDOM family. Source: dave-code-ruiz/elkbledom (Home Assistant) v1.6.5, models.json.
// Assumed for the three OPT7 Aura Pro boxes. Unverified on havok's hardware.
import { clampByte, clampPct } from './types';
import type { Bytes, LightDriver } from './types';

type Spec = {
  id: string;
  label: string;
  write: string;
  on: Bytes;
  off: Bytes;
  color: (r: number, g: number, b: number) => Bytes;
  bri: (i: number) => Bytes;
  init?: Bytes[];
  gap?: number;
};

const make = (s: Spec): LightDriver => ({
  id: s.id,
  label: s.label,
  write: [s.write],
  services: s.write === 'fff3' ? ['fff0'] : ['ffe0'],
  init: s.init?.map((bytes) => ({ bytes, delayMs: 1000 })),
  on: () => [...s.on],
  off: () => [...s.off],
  color: (r, g, b) => s.color(clampByte(r), clampByte(g), clampByte(b)),
  brightness: (pct) => s.bri(clampPct(pct)),
  writeGapMs: s.gap ?? 150,
});

